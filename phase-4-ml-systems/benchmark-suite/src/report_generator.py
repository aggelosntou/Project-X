"""
report_generator.py
===================
Generate a Markdown report from benchmark_results.json.

Usage:
    python3 src/report_generator.py [results.json] [output.md]

Defaults:
    results.json   -> benchmark_results.json
    output.md      -> benchmark_report.md
"""

import json
import sys
import os


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------

def _md_table(headers: list, rows: list) -> list:
    """Return lines for a Markdown table."""
    lines = []
    lines.append('| ' + ' | '.join(str(h) for h in headers) + ' |')
    lines.append('|' + '|'.join(['---'] * len(headers)) + '|')
    for row in rows:
        lines.append('| ' + ' | '.join(str(c) for c in row) + ' |')
    return lines


def _fmt_matmul(data: dict) -> list:
    """Format matmul benchmark section."""
    lines = ["\n## Matrix Multiply Benchmark\n"]
    rows_data = data.get('rows', [])
    if rows_data:
        lines += _md_table(
            ['N', 'GFLOPS', 'time_ms'],
            [[r['N'], r['gflops'], r['time_ms']] for r in rows_data],
        )
    peak = data.get('peak_gflops', 'N/A')
    lines.append(f"\n**Peak GFLOPS**: {peak}")
    return lines


def _fmt_attention(data: dict) -> list:
    """Format attention benchmark section."""
    lines = ["\n## Attention Benchmark\n"]
    rows_data = data.get('rows', [])
    if rows_data:
        lines += _md_table(
            ['seq_len', 'time_ms', 'mem_MB', 'GFLOPS'],
            [[r['seq_len'], r['time_ms'], r['mem_mb'], r['gflops']]
             for r in rows_data],
        )
    lines.append(
        "\n_Note: attention is memory-bandwidth bound "
        "(arithmetic intensity ≈ 0.25 FLOP/byte)._"
    )
    return lines


def _fmt_training(data: dict) -> list:
    """Format training benchmark section."""
    lines = ["\n## Training Step Benchmark\n"]
    bs = data.get('batch_size', 'N/A')
    total_ms = data.get('total_step_ms', 'N/A')
    sps = data.get('steps_per_sec', 'N/A')
    lines.append(f"Batch size: {bs}  |  Total step: {total_ms} ms  "
                 f"|  {sps} steps/sec\n")
    phases = data.get('phase_results', {})
    if phases:
        rows_data = [
            [phase, v['mean_ms'], v['std_ms'], f"{v['pct']}%"]
            for phase, v in phases.items()
        ]
        lines += _md_table(
            ['Phase', 'mean_ms', 'std_ms', '% of total'],
            rows_data,
        )
    return lines


def _fmt_inference(data: dict) -> list:
    """Format inference benchmark section."""
    lines = ["\n## Inference Benchmark\n"]
    rows_data = data.get('rows', [])
    if rows_data:
        lines += _md_table(
            ['batch_size', 'latency_ms/sample', 'throughput/s'],
            [[r['batch_size'], r['latency_ms'], r['throughput_s']]
             for r in rows_data],
        )
    lines.append(
        "\n_Latency drops with larger batch sizes as BLAS amortises "
        "fixed call overhead._"
    )
    return lines


# ---------------------------------------------------------------------------
# Main generator
# ---------------------------------------------------------------------------

def generate_report(
    results_path: str = 'benchmark_results.json',
    output_path:  str = 'benchmark_report.md',
) -> str:
    """
    Read results JSON and write a Markdown report.

    Returns the report as a string (also written to output_path).
    """
    if not os.path.exists(results_path):
        print(f"Results file not found: {results_path}", file=sys.stderr)
        print("Run 'python3 src/runner.py' first.", file=sys.stderr)
        sys.exit(1)

    with open(results_path) as f:
        r = json.load(f)

    lines = [
        "# Benchmark Report",
        "",
        f"Generated: {r.get('timestamp', 'N/A')}",
        "",
        "## System",
        "",
    ]

    # System info table
    sys_info = r.get('system', {})
    lines += _md_table(
        ['Property', 'Value'],
        [[k, v] for k, v in sys_info.items()],
    )

    # Individual benchmark sections
    lines += _fmt_matmul(r.get('matmul', {}))
    lines += _fmt_attention(r.get('attention', {}))
    lines += _fmt_training(r.get('training', {}))
    lines += _fmt_inference(r.get('inference', {}))

    # Footer
    lines += [
        "",
        "---",
        "_Generated by benchmark-suite/src/report_generator.py_",
    ]

    report = '\n'.join(lines)

    with open(output_path, 'w') as f:
        f.write(report)

    print(report)
    print(f"\nReport written to {output_path}")
    return report


if __name__ == '__main__':
    rp = sys.argv[1] if len(sys.argv) > 1 else 'benchmark_results.json'
    op = sys.argv[2] if len(sys.argv) > 2 else 'benchmark_report.md'
    generate_report(rp, op)
